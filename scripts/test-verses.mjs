import { readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { dirname, join } from "node:path"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")

// 畫面經文:「…」(可接 <br>)後面緊跟「——書名 章:節」或「(簡稱 章:節)」
const DISPLAY = /「[^」\n]{2,}」(?:<br>)?(?:——|\()[^\d\n「」]{1,8}?\s?\d+:\d+(?:-\d+)?\)?/g
// 語音稿:引號包住、裡面有「X章Y節。」或「X篇Y節。」的整句
const SPEECH = /(['"])((?:(?!\1)[^\n])*?[一二三四五六七八九十百零]+[章篇][一二三四五六七八九十百零到]+節。(?:(?!\1)[^\n])*)\1/g

function extract(file) {
  const src = readFileSync(join(root, file), "utf8")
  const display = new Set([...src.matchAll(DISPLAY)].map((m) => m[0]))
  const speech = new Set([...src.matchAll(SPEECH)].map((m) => m[2]))
  return { display: [...display], speech: [...speech] }
}

