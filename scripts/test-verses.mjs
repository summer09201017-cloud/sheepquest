  for (const s of EXPECT["index.html"].speech) {
    if (baked.has(s)) pass++
    else { fail++; console.log(`  🔴 index.html 的語音句沒在 gen-voice.mjs 烤過:\n     ${s}`) }
  }
  console.log(fail ? `\n🔴 經文/語音稿比對失敗 ${fail} 項(通過 ${pass} 項)` : `\n🟢 經文與語音稿 ${pass} 項全部和釘死的字串一致`)
